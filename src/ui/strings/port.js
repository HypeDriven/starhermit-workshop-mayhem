/** A locale's table with the port strings over it (nested groups merged). */
export function withPort(locale, table) {
  const add = PORT[locale] || en;
  const out = { ...table };
  for (const [k, v] of Object.entries(add)) out[k] = v && typeof v === 'object' ? { ...(table[k] || {}), ...v } : v;
  return out;
}
